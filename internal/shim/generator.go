// Package shim generates per-package-manager interception shim scripts.
package shim

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

// PackageManagers is the list of supported PMs per PRD D-02.
var PackageManagers = []string{
	"npm", "yarn", "pnpm",
	"pip", "pip3", "uv", "poetry",
	"cargo",
	"gem", "bundler",
	"go",
	"dotnet",
	"conda",
	// NuGet excluded pending OQ-EP-V4-03 audit
}

// shimTemplate generates a bash shim that:
//  1. Locates the real PM binary by walking PATH and skipping the shim directory.
//  2. Probes 127.0.0.1:{{ProxyPort}} via /dev/tcp to see if the local proxy is up.
//  3. If up: exports HTTPS_PROXY + HTTP_PROXY + PM-specific CA env vars and execs real PM.
//  4. If down + fail-open (default): execs real PM unmodified.
//  5. If down + fail-closed (PHOENIX_FAIL_MODE=closed): exits 1.
const shimTemplate = `#!/usr/bin/env bash
# Phoenix Supply Chain Firewall — {{.PM}} shim
# Generated by phoenix-firewall init. DO NOT EDIT manually.

# Bypass: exec real binary unmodified when bypass token is set
if [ -n "${PHOENIX_FIREWALL_BYPASS_TOKEN:-}" ]; then
    _SHIM_DIR="${HOME}/.local/bin"
    IFS=: read -ra _DIRS <<< "$PATH"
    for _d in "${_DIRS[@]}"; do
        [ "$_d" = "$_SHIM_DIR" ] && continue
        if [ -x "${_d}/{{.PM}}" ]; then
            exec "${_d}/{{.PM}}" "$@"
        fi
    done
    echo "[phoenix-firewall] cannot find real {{.PM}} in PATH" >&2; exit 127
fi

# Locate real {{.PM}} binary, skipping our shim directory
_SHIM_DIR="${HOME}/.local/bin"
_REAL=""
IFS=: read -ra _DIRS <<< "$PATH"
for _d in "${_DIRS[@]}"; do
    [ "$_d" = "$_SHIM_DIR" ] && continue
    if [ -x "${_d}/{{.PM}}" ]; then
        _REAL="${_d}/{{.PM}}"
        break
    fi
done

if [ -z "$_REAL" ]; then
    echo "[phoenix-firewall] cannot find real {{.PM}} (shim dir excluded from search)" >&2
    exit 127
fi

# Check if the local firewall proxy is listening on port {{.ProxyPort}}
if (exec 3<>/dev/tcp/127.0.0.1/{{.ProxyPort}}) 2>/dev/null; then
    exec 3>&- 2>/dev/null
    _CA="${HOME}/.config/phoenix-firewall/phoenix-ca.crt"
    export HTTPS_PROXY="http://127.0.0.1:{{.ProxyPort}}"
    export HTTP_PROXY="http://127.0.0.1:{{.ProxyPort}}"
{{.CAExports}}elif [ "${PHOENIX_FAIL_MODE:-open}" = "closed" ]; then
    echo "[phoenix-firewall] proxy unavailable — {{.PM}} blocked (PHOENIX_FAIL_MODE=closed)" >&2
    exit 1
fi

exec "$_REAL" "$@"
`

// Generator writes shim scripts to the given directory.
type Generator struct {
	OutputDir string
	ProxyPort int // defaults to 8080
}

type shimData struct {
	PM        string
	Ecosystem string
	ProxyPort int
	CAExports string // pre-rendered bash export lines
}

func (g *Generator) Generate() error {
	port := g.ProxyPort
	if port == 0 {
		port = 8080
	}
	tmpl, err := template.New("shim").Parse(shimTemplate)
	if err != nil {
		return fmt.Errorf("shim template parse: %w", err)
	}
	for _, pm := range PackageManagers {
		path := filepath.Join(g.OutputDir, pm)
		f, err := os.OpenFile(path, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0755)
		if err != nil {
			return fmt.Errorf("open shim %s: %w", pm, err)
		}
		data := shimData{
			PM:        pm,
			Ecosystem: ecosystemOf(pm),
			ProxyPort: port,
			CAExports: caExportsOf(pm),
		}
		if err := tmpl.Execute(f, data); err != nil {
			f.Close()
			return fmt.Errorf("write shim %s: %w", pm, err)
		}
		f.Close()
	}
	return nil
}

// caExportsOf returns pre-rendered bash export lines for the PM-specific CA env vars,
// each indented with 4 spaces and terminated with a newline.
func caExportsOf(pm string) string {
	vars := caEnvVarsOf(pm)
	if len(vars) == 0 {
		return ""
	}
	var sb strings.Builder
	for _, v := range vars {
		sb.WriteString(`    export `)
		sb.WriteString(v)
		sb.WriteString(`="${_CA}"`)
		sb.WriteByte('\n')
	}
	return sb.String()
}

// caEnvVarsOf returns the env var names that a PM uses to locate a custom CA bundle.
// Go is intentionally absent — it uses the system trust store with no override env var.
func caEnvVarsOf(pm string) []string {
	m := map[string][]string{
		"npm":     {"NODE_EXTRA_CA_CERTS"},
		"yarn":    {"NODE_EXTRA_CA_CERTS"},
		"pnpm":    {"NODE_EXTRA_CA_CERTS"},
		"pip":     {"PIP_CERT", "REQUESTS_CA_BUNDLE"},
		"pip3":    {"PIP_CERT", "REQUESTS_CA_BUNDLE"},
		"uv":      {"SSL_CERT_FILE"},
		"poetry":  {"REQUESTS_CA_BUNDLE"},
		"cargo":   {"CARGO_HTTP_CAINFO"},
		"gem":     {"SSL_CERT_FILE"},
		"bundler": {"BUNDLE_SSL_CA_CERT"},
		"dotnet":  {"SSL_CERT_FILE"},
		"conda":   {"SSL_CERT_FILE"},
	}
	if vars, ok := m[pm]; ok {
		return vars
	}
	return nil
}

func ecosystemOf(pm string) string {
	m := map[string]string{
		"npm": "npm", "yarn": "npm", "pnpm": "npm",
		"pip": "pypi", "pip3": "pypi", "uv": "pypi", "poetry": "pypi",
		"cargo":  "crates.io",
		"gem":    "rubygems", "bundler": "rubygems",
		"go":     "go",
		"dotnet": "nuget",
		"conda":  "conda",
	}
	if eco, ok := m[pm]; ok {
		return eco
	}
	return pm
}
